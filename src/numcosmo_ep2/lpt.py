import numpy as np

# Power scaled gaussian field -------------------------------------

def toyPower(k, sk=0.2, A=1):
    """
    Return a Gaussian toy power spectrum.

    Parameters
    ----------
    k : array_like
        Wavenumber magnitude.
    sk : float
        Characteristic cutoff scale.
    A : float
        Spectrum amplitude.

    Returns
    -------
    array_like
        P(k) = A exp[-(k/sk)^2].
    """
    return A*np.exp(-(k / sk)**2)

def fourierGrid(N, L):
    """
    Construct the Fourier grid for an N^3 real periodic mesh.

    Uses the NumPy rFFT layout, with full Fourier axes in x and y
    and the non-negative half-spectrum in z.

    Returns
    -------
    kxy, kz1d : ndarray
        One-dimensional Fourier axes.
    kx, ky, kz : ndarray
        Broadcastable Cartesian wavevector components.
    k2, kmag : ndarray
        Squared and absolute wavevector magnitudes.
    """
    dx = L / N

    kxy = 2.0 * np.pi * np.fft.fftfreq(N, d=dx)
    # z dimension arbitrarily chosen to be
    # compressed for hermitian symmetry in rfft
    kz1d = 2.0 * np.pi * np.fft.rfftfreq(N, d=dx)

    kx = kxy[:, None, None]
    ky = kxy[None, :, None]
    kz = kz1d[None, None, :]

    k2 = kx**2 + ky**2 + kz**2
    kmag = np.sqrt(k2)

    return kxy, kz1d, kx, ky, kz, k2, kmag

def gaussianField(N, L, powerSpectrum, seed=None):
    """
    Generate a Gaussian density field in a periodic cubic box.

    The returned Fourier coefficients use the physical convention
    <|delta_k|^2> = V P(k), with V = L^3. The field is generated by
    filtering real-space white noise in the NumPy rFFT representation.

    Parameters
    ----------
    N : int
        Number of mesh cells per dimension.
    L : float
        Box side length.
    powerSpectrum : callable
        Function returning P(k).
    seed : int, optional
        Random-number seed.

    Returns
    -------
    delta_k : ndarray
        Physical Fourier coefficients, shape (N, N, N//2 + 1).
    delta_x : ndarray
        Real-space density contrast, shape (N, N, N).
    """
    rng = np.random.default_rng(seed)

    dx = L / N
    V = L**3

    kxy, kz1d, kx, ky, kz, k2, kmag = fourierGrid(N, L)

    # Real-space white noise
    eta_x = rng.normal(size=(N, N, N))

    # NumPy FFT normalization
    eta_fft = np.fft.rfftn(eta_x)

    Pk = powerSpectrum(kmag)

    delta_fft = eta_fft * np.sqrt(Pk / dx**3)

    # Zero mean
    delta_fft[0, 0, 0] = 0.0

    delta_x = np.fft.irfftn(
        delta_fft,
        s=(N, N, N),
        axes=(0, 1, 2)
    )

    # Physical Fourier coefficients
    delta_k = dx**3 * delta_fft

    return delta_k, delta_x

def shellAveragePower(delta_k, kmag, L, N, bins):
    """
    Estimate the isotropic power spectrum by shell averaging.

    Accounts for the multiplicity of modes omitted by the rFFT
    half-spectrum. Fourier coefficients must use the physical
    normalization <|delta_k|^2> = V P(k).

    Returns
    -------
    kbin : ndarray
        Mean wavenumber in each non-empty shell.
    Pbin : ndarray
        Shell-averaged power spectrum.
    Nmodes : ndarray
        Effective number of full-spectrum modes in each shell.
    """
    V = L**3

    # Mode power in the physical convention
    Pmode = np.abs(delta_k)**2 / V

    # Multiplicity of the rFFT half-spectrum
    # (each non-zero and non-Nyquist term 
    # contributes with weight 2)
    wz = np.full(N // 2 + 1, 2.0)
    wz[0] = 1.0

    if N % 2 == 0:
        wz[-1] = 1.0

    weights = np.broadcast_to(wz[None, None, :], kmag.shape)

    # Remove zero mode
    mask = kmag > 0.0

    k = kmag[mask]
    p = Pmode[mask]
    w = weights[mask]

    Nmodes, _ = np.histogram(k, bins=bins, weights=w)
    Psum,   _ = np.histogram(k, bins=bins, weights=w * p)
    ksum,   _ = np.histogram(k, bins=bins, weights=w * k)

    valid = Nmodes > 0

    kbin = ksum[valid] / Nmodes[valid]
    Pbin = Psum[valid] / Nmodes[valid]

    return kbin, Pbin, Nmodes[valid]

def shellAverageInputPower(kmag, Pk, N, bins):
    """
    Shell-average an input power spectrum on the discrete Fourier grid.

    Uses the same rFFT mode multiplicities as `shellAveragePower`,
    allowing direct comparison between measured and input spectra.

    Returns
    -------
    kbin : ndarray
        Mean wavenumber in each non-empty shell.
    Pbin : ndarray
        Shell-averaged input power.
    """
    wz = np.full(N // 2 + 1, 2.0)
    wz[0] = 1.0

    if N % 2 == 0:
        wz[-1] = 1.0

    weights = np.broadcast_to(wz[None, None, :], kmag.shape)

    mask = kmag > 0.0

    k = kmag[mask]
    p = Pk[mask]
    w = weights[mask]

    Nmodes, _ = np.histogram(k, bins=bins, weights=w)
    Psum, _ = np.histogram(k, bins=bins, weights=w * p)
    ksum, _ = np.histogram(k, bins=bins, weights=w * k)

    valid = Nmodes > 0

    return (
        ksum[valid] / Nmodes[valid],
        Psum[valid] / Nmodes[valid]
    )

def removeNyquistModes(delta_k):
    """
    Remove the zero mode and Nyquist planes from an rFFT field.

    For even N, all modes lying on a Nyquist plane are set to zero.
    This defines the convention used for odd spectral derivatives.

    Parameters
    ----------
    delta_k : ndarray
        Fourier field in rFFT layout.

    Returns
    -------
    ndarray
        Filtered copy of the input field.
    """
    delta = delta_k.copy()
    N = delta.shape[0]

    delta[0, 0, 0] = 0.0

    if N % 2 == 0:
        delta[N//2, :, :] = 0.0
        delta[:, N//2, :] = 0.0
        delta[:, :,   -1] = 0.0

    return delta


# ZA displacements -----------------------------------------------------
    
def zaDisplacementFourier(delta_k, kx, ky, kz, k2, D1):
    """
    Compute the first-order Zel'dovich displacement in Fourier space.

    For nonzero modes,
        Psi_k = i D1 k delta_k / k^2.

    Nyquist modes are removed according to `removeNyquistModes`.

    Returns
    -------
    psi_k : ndarray
        Displacement Fourier coefficients, shape
        (3, N, N, N//2 + 1).
    delta_za : ndarray
        Density field after the adopted zero/Nyquist filtering.
    """
    delta_za = removeNyquistModes(delta_k)

    inv_k2 = np.zeros_like(k2)
    mask = k2 > 0.0
    inv_k2[mask] = 1.0 / k2[mask]

    psi_k = np.array([
        1j * D1 * kx * inv_k2 * delta_za,
        1j * D1 * ky * inv_k2 * delta_za,
        1j * D1 * kz * inv_k2 * delta_za
    ])

    # Zero mode must be identically zero
    psi_k[:, 0, 0, 0] = 0.0

    return psi_k, delta_za

def displacementToReal(psi_k, N, L):
    """
    Transform physical displacement coefficients to real space.

    Parameters
    ----------
    psi_k : ndarray
        Physical Fourier coefficients of the displacement.
    N : int
        Mesh size per dimension.
    L : float
        Box side length.

    Returns
    -------
    psi_x : ndarray
        Real-space displacement field, shape (3, N, N, N).
    """
    dx = L / N

    psi_x = np.empty((3, N, N, N))

    for i in range(3):
        psi_fft = psi_k[i] / dx**3
        psi_x[i] = np.fft.irfftn(
            psi_fft,
            s=(N, N, N),
            axes=(0, 1, 2)
        )

    return psi_x

def uniformLattice(N, L):
    """
    Construct an N^3 uniform particle lattice in a periodic box.

    Particle labels coincide with the displacement-mesh nodes.

    Returns
    -------
    q : ndarray
        Lagrangian particle coordinates, shape (N, N, N, 3).
    """
    dx = L / N
    q1d = dx * np.arange(N)

    qx, qy, qz = np.meshgrid(q1d, q1d, q1d, indexing="ij")
    return np.stack((qx, qy, qz), axis=-1)

def zaParticles(q, psi_p, L, Hconf_i, f_i):
    """
    Construct Zel'dovich particle positions and peculiar velocities.

    Positions are wrapped periodically into [0, L), while velocities
    follow v = Hconf_i f_i Psi.

    Returns
    -------
    x : ndarray
        Eulerian particle positions.
    v : ndarray
        Peculiar particle velocities.
    """
    x = (q + psi_p) % L
    v = Hconf_i * f_i * psi_p

    return x, v

def cicDeposit(positions, L, Ng, masses=None, return_mass_grid=False):
    """
    Deposit particles onto an Ng^3 mesh using cloud-in-cell assignment.

    Periodic boundaries are applied in all dimensions. If masses are
    omitted, all particles are assigned unit mass.

    Returns
    -------
    delta : ndarray
        Mesh density contrast, rho/<rho> - 1.
    rho : ndarray, optional
        CIC-deposited particle mass per mesh cell. Returned only when
        `return_mass_grid=True`.
    """
    dx = L / Ng

    positions = np.asarray(positions)
    Np = positions.shape[0]

    if masses is None:
        masses = np.ones(Np)

    u = positions / dx

    i0 = np.floor(u).astype(int)
    frac = u - i0

    rho = np.zeros((Ng, Ng, Ng), dtype=float)

    for sx in (0, 1):
        wx = (1.0 - frac[:, 0]) if sx == 0 else frac[:, 0]

        for sy in (0, 1):
            wy = (1.0 - frac[:, 1]) if sy == 0 else frac[:, 1]

            for sz in (0, 1):
                wz = (1.0 - frac[:, 2]) if sz == 0 else frac[:, 2]

                ix = (i0[:, 0] + sx) % Ng
                iy = (i0[:, 1] + sy) % Ng
                iz = (i0[:, 2] + sz) % Ng

                w = masses * wx * wy * wz
                np.add.at(rho, (ix, iy, iz), w)

    delta = rho / rho.mean() - 1.0

    if return_mass_grid:
        return delta, rho
    return delta

def cicWindow(kx, ky, kz, dx):
    """
    Return the Fourier-space cloud-in-cell assignment window.

    The three-dimensional window is the product of the squared
    one-dimensional sinc factors along each Cartesian direction.

    Returns
    -------
    ndarray
        CIC window evaluated on the Fourier grid.
    """
    Wx = np.sinc(kx * dx / (2.0 * np.pi))**2
    Wy = np.sinc(ky * dx / (2.0 * np.pi))**2
    Wz = np.sinc(kz * dx / (2.0 * np.pi))**2

    return Wx * Wy * Wz

# Ensamble analysis -----------------------------------------------------

def oneZaSpectrum(N, L, seed, D_i, classPower, bins):
    """
    Generate one paired Gaussian/ZA power-spectrum realization.

    A Gaussian reference field is drawn at the spectrum reference epoch,
    evolved linearly to the initial epoch through `D_i`, and used to
    construct first-order Zel'dovich displacements. A uniform particle
    lattice is displaced, deposited back onto an N^3 mesh with CIC, and
    the CIC Fourier window is deconvolved before measuring the particle
    power spectrum.

    The Gaussian and ZA spectra therefore share the same random phases
    and are evaluated at the same epoch.

    Parameters
    ----------
    N : int
        Mesh size and number of particles per dimension.
    L : float
        Periodic box side length.
    seed : int
        Random seed for the Gaussian realization.
    D_i : float
        Linear growth factor at the ZA initial epoch, normalized to
        D(a_ref) = 1.
    classPower : callable
        Reference linear power spectrum P(k, a_ref).
    bins : array_like
        Wavenumber bin edges used for shell averaging.

    Returns
    -------
    kbin : ndarray
        Mean wavenumber of each non-empty shell.
    Pg : ndarray
        Shell-averaged Gaussian linear power spectrum at the initial
        epoch.
    Pza : ndarray
        Shell-averaged ZA particle power spectrum after CIC
        deconvolution.
    Pinput : ndarray
        Shell-averaged theoretical input spectrum D_i^2 P(k, a_ref).
    Nmodes : ndarray
        Effective number of full-spectrum Fourier modes per shell.

    Notes
    -----
    No Poisson shot-noise subtraction is applied because the particle
    load is a displaced lattice rather than a Poisson sample.
    """
    dx = L / N
    V = L**3

    kxy, kz1d, kx, ky, kz, k2, kmag = fourierGrid(N, L)

    # Gaussian reference realization at a_ref = 1
    delta_ref_k, _ = gaussianField(
        N, L, classPower, seed=seed
    )

    # ZA at a_i
    psi_k, delta_used = zaDisplacementFourier(
        delta_ref_k,
        kx, ky, kz,
        k2,
        D_i
    )

    psi_x = displacementToReal(psi_k, N, L)

    # Gaussian linear field at the SAME epoch
    delta_linear_k = D_i * delta_used

    # Uniform lattice
    q = uniformLattice(N, L)
    psi_p = np.moveaxis(psi_x, 0, -1)

    # Positions only; velocities are irrelevant for P(k)
    x_p = (q + psi_p) % L

    # CIC assignment
    delta_za_x = cicDeposit(x_p.reshape(-1, 3), L, N)

    delta_za_k = dx**3 * np.fft.rfftn(delta_za_x)

    # CIC deconvolution
    Wcic = cicWindow(kx, ky, kz, dx)

    delta_za_k_corrected = np.zeros_like(delta_za_k)

    mask = Wcic > 0.0
    delta_za_k_corrected[mask] = delta_za_k[mask] / Wcic[mask]

    delta_za_k_corrected[0, 0, 0] = 0.0

    # Shell averages
    kbin, Pg, Nmodes = shellAveragePower(
        delta_linear_k,
        kmag,
        L,
        N,
        bins
    )

    _, Pza, _ = shellAveragePower(
        delta_za_k_corrected,
        kmag,
        L,
        N,
        bins
    )

    # Shell-averaged theoretical spectrum at a_i
    Pinput_grid = D_i**2 * classPower(kmag)

    _, Pinput = shellAverageInputPower(
        kmag,
        Pinput_grid,
        N,
        bins
    )

    return kbin, Pg, Pza, Pinput, Nmodes

def runZaEnsemble(N, L, seeds, D_i, classPower):
    """
    Run an ensemble of paired Gaussian and ZA spectrum realizations.

    For each random seed, `oneZaSpectrum` is evaluated using identical
    box, resolution, growth factor, spectrum, and shell definition.
    Power spectra are measured only up to 0.5 k_Ny, where

        k_Ny = pi N / L.

    Parameters
    ----------
    N : int
        Mesh and particle resolution per dimension.
    L : float
        Periodic box side length.
    seeds : iterable of int
        Random seeds defining independent Gaussian realizations.
    D_i : float
        Linear growth factor at the ZA initial epoch.
    classPower : callable
        Reference linear power spectrum P(k, a_ref).

    Returns
    -------
    result : dict
        Dictionary containing:

        `N`
            Mesh resolution.
        `k`
            Shell-averaged wavenumbers.
        `Pinput`
            Shell-averaged theoretical spectrum at the initial epoch.
        `Nmodes`
            Effective number of Fourier modes per shell.
        `Pg`
            Gaussian spectra with shape (Nseed, Nbin).
        `Pza`
            ZA particle spectra with shape (Nseed, Nbin).

    Notes
    -----
    The upper analysis limit of 0.5 k_Ny is an operational choice and
    should not be interpreted as a universal accuracy threshold.
    """
    kf = 2.0 * np.pi / L
    kNy = np.pi * N / L
    kmax = 0.5 * kNy

    bins = np.arange(0.5 * kf, kmax + 1.5 * kf, kf)

    Pg_all = []
    Pza_all = []

    for seed in seeds:
        kbin, Pg, Pza, Pinput, Nmodes = oneZaSpectrum(
            N,
            L,
            seed,
            D_i,
            classPower,
            bins
        )

        Pg_all.append(Pg)
        Pza_all.append(Pza)

    Pg_all = np.asarray(Pg_all)
    Pza_all = np.asarray(Pza_all)

    return {
        "N": N,
        "k": kbin,
        "Pinput": Pinput,
        "Nmodes": Nmodes,
        "Pg": Pg_all,
        "Pza": Pza_all,
    }

def ensembleStatistics(result):
    """
    Compute ensemble statistics for paired Gaussian and ZA spectra.

    The routine returns ensemble means and standard errors of the mean
    for both spectra. It also forms the realization-by-realization ratio

        P_ZA(k) / P_G(k),

    before averaging, so that fluctuations shared by the paired
    Gaussian and ZA fields are partially cancelled.

    Parameters
    ----------
    result : dict
        Output dictionary returned by `runZaEnsemble`.

    Returns
    -------
    stats : dict
        Dictionary containing:

        `Pg_mean`
            Ensemble-mean Gaussian power spectrum.
        `Pg_sem`
            Standard error of the Gaussian ensemble mean.
        `Pza_mean`
            Ensemble-mean ZA particle power spectrum.
        `Pza_sem`
            Standard error of the ZA ensemble mean.
        `paired_mean`
            Ensemble mean of the paired ratio P_ZA / P_G.
        `paired_sem`
            Standard error of the paired ratio.

    Notes
    -----
    The paired ratio is computed before ensemble averaging and is
    therefore distinct from Pza_mean / Pg_mean.
    """
    Pg = result["Pg"]
    Pza = result["Pza"]

    nseed = Pg.shape[0]

    Pg_mean = Pg.mean(axis=0)
    Pg_sem = Pg.std(axis=0, ddof=1) / np.sqrt(nseed)

    Pza_mean = Pza.mean(axis=0)
    Pza_sem = Pza.std(axis=0, ddof=1) / np.sqrt(nseed)

    paired_ratio = Pza / Pg

    paired_mean = paired_ratio.mean(axis=0)
    paired_sem = (
        paired_ratio.std(axis=0, ddof=1)
        / np.sqrt(nseed)
    )

    return {
        "Pg_mean": Pg_mean,
        "Pg_sem": Pg_sem,
        "Pza_mean": Pza_mean,
        "Pza_sem": Pza_sem,
        "paired_mean": paired_mean,
        "paired_sem": paired_sem,
    }